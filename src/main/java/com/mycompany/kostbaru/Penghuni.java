public class Penghuni {
    
    private String id;
    private String nama;

    public Penghuni(String id, String nama) {
        this.id = id;
        this.nama = nama;
    }

    public String getId() {
        return id;
    }

    public String getNama() {
        return nama;
    }

    public void tampilkanInfo() {
        System.out.println("ID Penghuni: " + id);
        System.out.println("Nama: " + nama);
    }
}